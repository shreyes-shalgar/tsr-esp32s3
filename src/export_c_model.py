"""
Emit the int8 network as dependency-free C (weights + layer table).

Output:
  tsr_model_data.h / tsr_model_data.c

The generated data is consumed by the hand-written runtime in tsr_model.c.
Buffer sizes are computed here by simulating the ping-pong allocation so the
firmware carries the exact minimum static RAM.
"""
import os, sys, argparse
import numpy as np
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from extract_params import extract

# Paths are resolved relative to the repository root so the scripts run
# from a fresh checkout on any machine.
_REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


def _p(*parts):
    return os.path.join(_REPO, *parts)


CLASS_IDS = [0, 2, 3, 4, 5, 6, 7, 24, 43, 69, 70, 72, 83, 84, 85, 86, 87]
# Labels are taken verbatim from the organisers' new_labels.csv.
CLASS_NAMES = [
    "Speed limit (5km/h)", "Speed limit (30km/h)", "Speed limit (40km/h)",
    "Speed limit (50km/h)", "Speed limit (60km/h)", "Speed limit (70km/h)",
    "speed limit (80km/h)", "Go Right", "Go right or straight",
    "Height limit", "Weight limit", "Length limit", "Steep descent",
    "Steep ascent", "Narrow road", "Narrow bridge", "Unknown",
]
OPS = {"conv": 0, "maxpool": 1, "avgpool": 2, "fc": 3}


def carr(name, arr, ctype):
    v = np.asarray(arr).reshape(-1)
    s = [f"const {ctype} {name}[{v.size}] = {{"]
    per = 16 if ctype == "int8_t" else 8
    for i in range(0, v.size, per):
        s.append("  " + ",".join(f"{int(x):d}" for x in v[i:i + per]) + ",")
    s.append("};")
    return "\n".join(s)


def numel(shape):
    n = 1
    for v in shape:
        n *= int(v)
    return n


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--tflite", default=_p("model", "model_int8.tflite"))
    ap.add_argument("--outdir", required=True)
    a = ap.parse_args()
    os.makedirs(a.outdir, exist_ok=True)
    P = extract(a.tflite)
    layers = P["layers"]

    assert P["in_scale"] == 1.0 and P["in_zp"] == -128, \
        "firmware assumes input int8 = pixel - 128"

    # ---- ping-pong buffer simulation -----------------------------------
    # A CONV immediately followed by a 2x2/stride-2 MAX_POOL is executed as one
    # fused pass: two convolution rows at a time into a small scratch, pooled
    # straight into the destination. The wide intermediate is never allocated.
    # The runtime applies exactly this rule when walking the layer table.
    def fuses_with_next(i):
        if i + 1 >= len(layers):
            return False
        a, b = layers[i], layers[i + 1]
        return (a["op"] == "conv" and b["op"] == "maxpool"
                and b["k"] == 2 and b["stride"] == 2)

    # CONV -> CONV -> 2x2/s2 MAX_POOL goes one step further: the first
    # convolution's output is never materialised either, only the four rows
    # of it the second convolution is currently reading. The second
    # convolution has to be 3x3 stride 1 pad 1 for that window to be exact.
    def fuses_triple(i):
        if i + 2 >= len(layers):
            return False
        a, b, c = layers[i], layers[i + 1], layers[i + 2]
        if not (a["op"] == "conv" and b["op"] == "conv"
                and c["op"] == "maxpool" and c["k"] == 2 and c["stride"] == 2):
            return False
        # k and pad are derived for conv exactly as they are when the layer
        # table is emitted below, so guard and table cannot disagree.
        kb, sb = int(b["W"].shape[1]), int(b["stride"])
        padb = max(0, (int(b["out_shape"][0]) - 1) * sb + kb
                   - int(b["in_shape"][0])) // 2
        return kb == 3 and sb == 1 and padb == 1

    scratch = 0
    effective = []          # (output_size) of each executed step
    i = 0
    while i < len(layers):
        if fuses_triple(i):
            c1, c2, pool = layers[i], layers[i + 1], layers[i + 2]
            r1 = int(c1["out_shape"][1]) * int(c1["out_shape"][2])
            r2 = int(c2["out_shape"][1]) * int(c2["out_shape"][2])
            scratch = max(scratch, 4 * r1 + 2 * r2)
            effective.append(numel(pool["out_shape"]))
            i += 3
        elif fuses_with_next(i):
            conv, pool = layers[i], layers[i + 1]
            # two convolution output rows held at once
            row = int(conv["out_shape"][1]) * int(conv["out_shape"][2])
            scratch = max(scratch, 2 * row)
            effective.append(numel(pool["out_shape"]))
            i += 2
        else:
            effective.append(numel(layers[i]["out_shape"]))
            i += 1

    # The first convolution reads the received image in place, so the input
    # tensor never occupies an arena buffer.
    need = [0, 0]
    slot = 1
    for o in effective:
        slot ^= 1
        need[slot] = max(need[slot], o)
    bufA, bufB = need[0], need[1]

    hdr = [
        "/* Auto-generated by export_c_model.py - do not edit. */",
        "#ifndef TSR_MODEL_DATA_H", "#define TSR_MODEL_DATA_H",
        "#include <stdint.h>", "",
        f"#define TSR_IMG_H {layers[0]['in_shape'][0]}",
        f"#define TSR_IMG_W {layers[0]['in_shape'][1]}",
        f"#define TSR_IMG_C {layers[0]['in_shape'][2]}",
        f"#define TSR_IMG_BYTES ({numel(layers[0]['in_shape'])})",
        f"#define TSR_NUM_CLASSES {len(CLASS_IDS)}",
        f"#define TSR_NUM_LAYERS {len(layers)}",
        f"#define TSR_BUF_A {bufA}",
        f"#define TSR_BUF_B {bufB}",
        f"#define TSR_SCRATCH {scratch}",
        f"#define TSR_ARENA_BYTES ({bufA} + {bufB} + {scratch})", "",
        "typedef enum { TSR_OP_CONV=0, TSR_OP_MAXPOOL=1,",
        "               TSR_OP_AVGPOOL=2, TSR_OP_FC=3 } tsr_op_t;", "",
        "typedef struct {",
        "  uint8_t  op, stride, ksize, pad;",
        "  uint16_t in_h, in_w, in_c;",
        "  uint16_t out_h, out_w, out_c;",
        "  const int8_t  *w;",
        "  const int32_t *bias;",
        "  const int32_t *mult;",
        "  const int32_t *shift;",
        "  int16_t in_zp, out_zp;",
        "} tsr_layer_t;", "",
        "extern const tsr_layer_t tsr_layers[TSR_NUM_LAYERS];",
        "extern const int16_t tsr_class_ids[TSR_NUM_CLASSES];",
        "extern const char *const tsr_class_names[TSR_NUM_CLASSES];",
        "",
        "/* Output dequantisation, for the confidence figure. */",
        f"#define TSR_OUT_SCALE {P['out_scale']:.10g}f",
        f"#define TSR_OUT_ZP ({P['out_zp']})",
        "#endif /* TSR_MODEL_DATA_H */", ""]
    open(os.path.join(a.outdir, "tsr_model_data.h"), "w").write("\n".join(hdr))

    src = ["/* Auto-generated by export_c_model.py - do not edit. */",
           '#include "tsr_model_data.h"', "",
           carr("tsr_class_ids", CLASS_IDS, "int16_t"), "",
           "const char *const tsr_class_names[TSR_NUM_CLASSES] = {"]
    for n in CLASS_NAMES:
        src.append(f'  "{n}",')
    src += ["};", ""]
    wbytes = 0
    for i, L in enumerate(layers):
        if L["op"] in ("conv", "fc"):
            src.append(carr(f"w{i}", L["W"], "int8_t"))
            src.append(carr(f"b{i}", L["B"], "int32_t"))
            src.append(carr(f"m{i}", L["mult"], "int32_t"))
            src.append(carr(f"s{i}", L["shift"], "int32_t"))
            src.append("")
            wbytes += L["W"].size + 4 * (L["B"].size + L["mult"].size + L["shift"].size)

    src.append(f"const tsr_layer_t tsr_layers[TSR_NUM_LAYERS] = {{")
    for i, L in enumerate(layers):
        ish, osh = L["in_shape"], L["out_shape"]
        if L["op"] == "conv":
            K = int(L["W"].shape[1]); S = int(L["stride"])
            pad = max(0, (int(osh[0]) - 1) * S + K - int(ish[0])) // 2
            src.append(f"  {{ TSR_OP_CONV, {S}, {K}, {pad}, "
                       f"{ish[0]},{ish[1]},{ish[2]}, {osh[0]},{osh[1]},{osh[2]}, "
                       f"w{i}, b{i}, m{i}, s{i}, {L['in_zp']}, {L['out_zp']} }},")
        elif L["op"] in ("maxpool", "avgpool"):
            tag = "TSR_OP_MAXPOOL" if L["op"] == "maxpool" else "TSR_OP_AVGPOOL"
            k = int(L["k"])
            src.append(f"  {{ {tag}, {k}, {k}, 0, "
                       f"{ish[0]},{ish[1]},{ish[2]}, {osh[0]},{osh[1]},{osh[2]}, "
                       f"0, 0, 0, 0, 0, 0 }},")
        else:
            src.append(f"  {{ TSR_OP_FC, 1, 1, 0, 1,1,{ish[0]}, 1,1,{osh[0]}, "
                       f"w{i}, b{i}, m{i}, s{i}, {L['in_zp']}, {L['out_zp']} }},")
    src.append("};")
    open(os.path.join(a.outdir, "tsr_model_data.c"), "w").write("\n".join(src) + "\n")

    print(f"layers        : {len(layers)}")
    print(f"weight bytes  : {wbytes}")
    print(f"buffer A / B  : {bufA} / {bufB}  scratch {scratch}"
          f"   arena = {bufA + bufB + scratch} bytes")
    print(f"written to    : {a.outdir}")


if __name__ == "__main__":
    main()
